package com.obj.nc.security;

import com.obj.nc.security.config.JwtTokenUtil;
import com.obj.nc.security.config.NcJwtConfigProperties;
import org.junit.jupiter.api.Test;
import org.springframework.security.core.userdetails.User;

import java.nio.charset.StandardCharsets;
import java.util.Base64;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class JwtTokenCompatibilityTest {
    private static final String SECRET = Base64.getEncoder().encodeToString(
            "notiflow-test-signing-secret-for-hs512-at-least-64-bytes-long-1234567890"
                    .getBytes(StandardCharsets.UTF_8));
    // Generated by the original JJWT 0.9.1 on Java 8, with expiry 2030-01-01.
    private static final String LEGACY_TOKEN = "eyJhbGciOiJIUzUxMiJ9.eyJzdWIiOiJ0ZXN0VXNlciIsImlhdCI6MTcwNDA2NzIwMCwiZXhwIjoxODkzNDU2MDAwfQ.Hn83W01sdJtB5lorYebE_4EI59nwFzZYYFjoxaIJ1eRsBFviOJBhlg16WAsaTl8cvOx9hujkJqWfzWQpZcvqcg";

    private JwtTokenUtil tokens() {
        var properties = new NcJwtConfigProperties();
        properties.setSignatureSecret(SECRET);
        return new JwtTokenUtil(properties);
    }

    @Test
    void acceptsTokensIssuedByTheLegacyApplicationWithTheSameBase64Key() {
        assertThat(tokens().getUsernameFromToken(LEGACY_TOKEN)).isEqualTo("testUser");
        assertThat(tokens().validateToken(LEGACY_TOKEN, User.withUsername("testUser").password("unused").roles("USER").build()))
                .isTrue();
    }

    @Test
    void issuesAndValidatesHs512Tokens() {
        var user = User.withUsername("testUser").password("unused").roles("USER").build();
        var tokens = tokens();
        String token = tokens.generateToken(user, SECRET);
        assertThat(tokens.validateToken(token, user)).isTrue();
        assertThat(tokens.getExpirationDateFromToken(token)).isAfter(new java.util.Date());
    }

    @Test
    void rejectsWeakSigningKeysWithAnActionableConfigurationError() {
        var user = User.withUsername("testUser").password("unused").roles("USER").build();
        assertThatThrownBy(() -> tokens().generateToken(user, "testSecret"))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("at least 64 bytes");
    }

    @Test
    void rejectsWeakSigningKeysAtStartupOnlyWhenJwtIsEnabled() {
        var properties = new NcJwtConfigProperties();
        properties.setSignatureSecret("testSecret");
        new JwtTokenUtil(properties).validateSignatureSecret();

        properties.setEnabled(true);
        assertThatThrownBy(() -> new JwtTokenUtil(properties).validateSignatureSecret())
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("at least 64 bytes");
    }
}
